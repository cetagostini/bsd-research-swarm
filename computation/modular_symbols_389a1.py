# Part 11: Consistency Checks
# ═══════════════════════════════════════════════════════════════════════

def verify_hecke_eigenvalues(ap_dict, n_checks=20):
    """
    Verify Hecke eigenvalue consistency.

    For the newform f, we check:
    1. a_p ∈ Z for all p
    2. |a_p| ≤ 2√p (Hasse bound)
    3. Multiplicativity: a_{p²} = a_p² − p for p ∤ N
    """
    primes = sorted(ap_dict.keys())
    checks = []

    for p in primes[:n_checks]:
        ap = ap_dict[p]
        # Hasse bound
        hasse_ok = abs(ap) <= 2 * sqrt(p) + 0.5
        # Integer
        integer_ok = ap == int(ap)

        checks.append({
            "p": p,
            "a_p": int(ap),
            "hasse_bound": f"|{ap}| ≤ {float(2*sqrt(p)):.2f}",
            "hasse_ok": hasse_ok,
            "integer_ok": integer_ok,
        })

    return checks


def verify_functional_equation(a_coeffs, N_terms=500):
    """
    Verify Λ(E, s) = Λ(E, 2−s) numerically.

    The completed L-function should satisfy the functional equation.
    We check at s = 3/2 (away from the central point) where the
    series converges well.
    """
    s1 = mpf('1.5')
    s2 = mpf('0.5')  # 2 − 1.5

    L1 = L_at_s(a_coeffs, s1, N_terms)
    L2 = L_at_s(a_coeffs, s2, N_terms)

    Lambda1 = completed_L_factor(s1) * L1
    Lambda2 = completed_L_factor(s2) * L2

    return {
        "s_values": (float(s1), float(s2)),
        "Lambda_s": float(Lambda1),
        "Lambda_2_minus_s": float(Lambda2),
        "ratio": float(Lambda1 / Lambda2) if Lambda2 != 0 else None,
        "functional_eq_holds": abs(float(Lambda1 / Lambda2) - 1) < 0.1
        if Lambda2 != 0 else False,
    }


