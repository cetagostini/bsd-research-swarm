def completed_L_factor(s):
    """
    The gamma factor for the completed L-function:
      Λ(E, s) = (N/(2π)²)^{s/2} · Γ(s) · L(E, s)

    Returns (N/(2π)²)^{s/2} · Γ(s).
    """
    s = mpf(s)
    N_half = mpf(N_CONDUCTOR) / (4 * pi * pi)
    return power(N_half, s / 2) * gamma(s)


def approximate_functional_equation(a_coeffs, s, N_terms=1000):
    """
    Approximate functional equation for L(E, s) at s near 1.

    The completed L-function Λ(E, s) = ε · Λ(E, 2−s) gives:

      L(E, s) = Σ_{n≥1} a_n/n^s · W₁(n√N/(2π), s)
               + ε · (N/(2π)²)^{1−s} · Γ(1−s)/Γ(s)
                 · Σ_{n≥1} a_n/n^{2−s} · W₂(n√N/(2π), 2−s)

    where W₁, W₂ are smooth cutoff functions (inverse Mellin transforms
    of Γ-factors).

    For s near 1, both sums contribute, and the functional equation
    provides a consistency check: Λ(E, s) = Λ(E, 2−s).

    Parameters
    ----------
    a_coeffs : list
        Fourier coefficients a_n.
    s : complex
        Point of evaluation (typically near s = 1).
    N_terms : int
        Number of terms in each sum.

    Returns
    -------
    L_approx : mpc
        Numerical approximation to L(E, s).
    """
    s = mpc(s)
    N = N_CONDUCTOR
    sqrt_N_over_2pi = sqrt(mpf(N)) / (2 * pi)

    # Smooth weight function: W(x, s) ≈ exp(−x²) for the truncated sum.
    # This is a simplification; the exact W involves incomplete gamma functions.
    def smooth_weight(x, s_val):
        """Gaussian approximation to the AFE weight."""
        x = mpf(x)
        return exp(-x * x)

    # ε-factor (root number)
    eps = mpf(ROOT_NUMBER)

    # Sum 1: Σ a_n / n^s · W(n√N/(2π))
    sum1 = mpf(0)
    for n in range(1, N_terms + 1):
        if n >= len(a_coeffs):
            break
        an = a_coeffs[n]
        if an == 0:
            continue
        x_n = mpf(n) * sqrt_N_over_2pi
        w = smooth_weight(x_n, s)
        sum1 += mpf(an) * w / power(mpf(n), s)

    # Sum 2 (dual): Σ a_n / n^{2-s} · W(n√N/(2π))
    sum2 = mpf(0)
    for n in range(1, N_terms + 1):
        if n >= len(a_coeffs):
            break
        an = a_coeffs[n]
        if an == 0:
            continue
        x_n = mpf(n) * sqrt_N_over_2pi
        w = smooth_weight(x_n, 2 - s)
        sum2 += mpf(an) * w / power(mpf(n), 2 - s)

    # Correction factor from functional equation
    gamma_ratio = gamma(1 - s) / gamma(s)
    N_factor = power(mpf(N) / (4 * pi * pi), 1 - s)

    return sum1 + eps * N_factor * gamma_ratio * sum2


