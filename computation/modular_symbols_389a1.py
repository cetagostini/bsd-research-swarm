def gcd(a, b):
    """Euclidean GCD."""
    while b:
        a, b = b, a % b
    return a


def enumerate_manin_symbols(N, verbose=False):
    """
    Enumerate the Manin symbol generators [u, v] for Γ₀(N).

    A Manin symbol is a pair (u, v) mod N with the equivalence:
      [u, v] ~ [u + N, v] ~ [u, v + N]
    and the SL₂(Z) relations.

    The total number of unreduced symbols is N² (all pairs mod N).
    After imposing gcd(u, v, N) = 1 and SL₂(Z) relations, the count
    is much smaller.

    For Γ₀(N) with prime N, the number of generators modulo relations
    is related to the dimension of H₁(X₀(N), cusps; Q).

    This function enumerates representatives for documentation; the
    actual reduction requires solving a linear system over Q.
    """
    generators = []
    for u in range(N):
        for v in range(N):
            if gcd(gcd(u, v), N) == 1:
                generators.append((u, v))

    if verbose:
        print(f"  Raw Manin symbols for Γ₀({N}): {len(generators)}")
        print(f"  After SL₂(Z) relations: ~{len(generators) // 6} (estimate)")
        print(f"  dim H₁(X₀({N}), cusps; Q) = {2 * GENUS + 1}")  # 2g + cusps - 1

    return generators


