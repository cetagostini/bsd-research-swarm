def L_at_s(a_coeffs, s, N_terms=1000):
    """
    Compute L(E, s) via the approximate functional equation.

    For s = 1 with root number +1, L(E, 1) should be 0 for 389.a1.
    """
    return approximate_functional_equation(a_coeffs, s, N_terms)


def L_derivative_numerical(a_coeffs, s0=1, h=mpf('1e-8'), N_terms=1000):
    """
    Estimate L'(E, s0) by numerical differentiation (central difference).

    L'(1) ≈ [L(1+h) − L(1−h)] / (2h)

    This is numerically unstable near a zero of L, but serves as a
    consistency check.
    """
    L_plus = L_at_s(a_coeffs, s0 + h, N_terms)
    L_minus = L_at_s(a_coeffs, s0 - h, N_terms)
    return (L_plus - L_minus) / (2 * h)


def L_second_derivative_numerical(a_coeffs, s0=1, h=mpf('1e-5'), N_terms=1000):
    """
    Estimate L''(E, s0) by central difference:

    L''(1) ≈ [L(1+h) − 2·L(1) + L(1−h)] / h²
    """
    L_plus = L_at_s(a_coeffs, s0 + h, N_terms)
    L_center = L_at_s(a_coeffs, s0, N_terms)
    L_minus = L_at_s(a_coeffs, s0 - h, N_terms)
    return (L_plus - 2 * L_center + L_minus) / (h * h)


