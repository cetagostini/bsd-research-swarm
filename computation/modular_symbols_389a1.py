def count_points_389a1(p):
    """
    Count #E(F_p) for E: y^2 + y = x^3 + x^2 - 2x over F_p.

    For each x ∈ F_p, count the number of y ∈ F_p satisfying the curve
    equation (including the point at infinity).
    """
    count = 1  # point at infinity
    for x in range(p):
        # RHS: x^3 + x^2 - 2x mod p
        rhs = (pow(x, 3, p) + pow(x, 2, p) - 2 * x) % p
        # LHS: y^2 + y = rhs  =>  (2y+1)^2 = 4*rhs + 1
        disc = (4 * rhs + 1) % p
        if disc == 0:
            count += 1  # one solution
        else:
            # Legendre symbol
            ls = pow(disc, (p - 1) // 2, p)
            if ls == 1:
                count += 2  # two solutions
            # else ls == p-1, no solutions
    return count


def ap_from_count(p):
    """Compute a_p = p + 1 - #E(F_p)."""
    return p + 1 - count_points_389a1(p)


def sieve_primes(limit):
    """Simple sieve of Eratosthenes."""
    is_prime = [True] * (limit + 1)
    is_prime[0] = is_prime[1] = False
    for i in range(2, int(limit**0.5) + 1):
        if is_prime[i]:
            for j in range(i * i, limit + 1, i):
                is_prime[j] = False
    return [i for i in range(2, limit + 1) if is_prime[i]]


